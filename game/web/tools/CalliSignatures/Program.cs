// Writes the DllImport anchors the browser player needs for the calli sites of its script assemblies.
//
// The engine's script API reaches native code through calli on unmanaged function pointers (the icall weaver).
// The .NET browser runtime interprets C#, and its interpreter calls native code through a trampoline per signature
// that the build generates when it relinks the runtime. It generates them for DllImport signatures only, not for
// calli sites, and a missing one ends the process. One unused DllImport per signature, to a module that does not
// exist, makes the relink generate them all.
//
// The signature string follows the relink's own mapping: int-sized values and pointers are I, 64-bit integers L,
// float F, double D, void V; a struct with one field maps as that field, any other struct is passed by pointer (I),
// and a struct result becomes a leading result pointer (VI).
//
//   CalliSignatures <output .cs> <runtime pack lib folder> [--weave-with <bridge>] <assembly>...
//
// With --weave-with, each assembly but the bridge is first woven in place by the bridge's own weaver, as the editor
// weaves the scripts it compiles (Clrpp.Bridge.WeaveAssembly): the calli sites are the weaver's.
using System.Reflection;
using System.Runtime.InteropServices;
using Mono.Cecil;
using Mono.Cecil.Cil;

const int MAX_STRUCT_DEPTH = 5;
const string WEAVE_OPTION = "--weave-with";

var arguments = args.ToList();
string? bridgePath = null;
var weaveIndex = arguments.IndexOf(WEAVE_OPTION);
if(weaveIndex >= 0 && weaveIndex + 1 < arguments.Count)
{
    bridgePath = Path.GetFullPath(arguments[weaveIndex + 1]);
    arguments.RemoveRange(weaveIndex, 2);
}
if(arguments.Count < 3)
{
    Console.Error.WriteLine($"usage: CalliSignatures <output .cs> <runtime pack lib folder> [{WEAVE_OPTION} <bridge>] <assembly>...");
    return 1;
}

var outputPath = arguments[0];
var assemblies = arguments.Skip(2).ToList();
if(bridgePath != null)
{
    foreach(var assemblyPath in assemblies.Where(path => !IsSameFile(path, bridgePath)))
    {
        if(!Weave(bridgePath, assemblyPath))
        {
            Console.Error.WriteLine($"weaving {assemblyPath} failed");
            return 1;
        }
    }
}
var resolver = new DefaultAssemblyResolver();
resolver.AddSearchDirectory(arguments[1]);
foreach(var assemblyPath in assemblies)
{
    resolver.AddSearchDirectory(Path.GetDirectoryName(Path.GetFullPath(assemblyPath))!);
}

var signatures = new SortedSet<string>(StringComparer.Ordinal);
foreach(var assemblyPath in assemblies)
{
    using var module = ModuleDefinition.ReadModule(assemblyPath, new ReaderParameters { AssemblyResolver = resolver });
    var callSites = 0;
    foreach(var type in module.GetTypes())
    {
        foreach(var method in type.Methods.Where(m => m.HasBody))
        {
            foreach(var instruction in method.Body.Instructions.Where(i => i.OpCode == OpCodes.Calli))
            {
                var site = (CallSite)instruction.Operand;
                if(site.CallingConvention == MethodCallingConvention.Default)
                {
                    continue;
                }
                signatures.Add(ToSignature(site.ReturnType, site.Parameters.Select(p => p.ParameterType)));
                ++callSites;
            }
        }
    }
    Console.WriteLine($"{Path.GetFileName(assemblyPath)}: {callSites} unmanaged calli sites");
}

using(var writer = new StreamWriter(outputPath))
{
    writer.WriteLine("// <auto-generated> by game/web/tools/CalliSignatures from the script assemblies' calli sites.");
    writer.WriteLine("namespace Unravel.Web");
    writer.WriteLine("{");
    writer.WriteLine("    /// Never called: one DllImport per calli signature of the script assemblies, to a module that does not");
    writer.WriteLine("    /// exist, so the relink generates the interpreter-to-native trampoline each calli needs.");
    writer.WriteLine("    internal static class CalliSignatures");
    writer.WriteLine("    {");
    writer.WriteLine("        private const string MODULE = \"unravel_calli_signatures\";");
    foreach(var signature in signatures)
    {
        writer.WriteLine();
        writer.WriteLine("        [System.Runtime.InteropServices.DllImport(MODULE)]");
        writer.WriteLine($"        internal static extern {ToCSharp(signature[0])} S_{signature}({ToParameters(signature.Substring(1))});");
    }
    writer.WriteLine("    }");
    writer.WriteLine("}");
}
Console.WriteLine($"{signatures.Count} signatures written to {outputPath}");
return 0;

static bool IsSameFile(string path, string other)
{
    return string.Equals(Path.GetFullPath(path), other, StringComparison.OrdinalIgnoreCase);
}

// The bridge's weaver is an unmanaged entry point: it is called through its function pointer.
static unsafe bool Weave(string bridgePath, string assemblyPath)
{
    var bridge = Assembly.LoadFrom(bridgePath);
    var method = bridge.GetType("Clrpp.Bridge")?.GetMethod("WeaveAssembly", BindingFlags.Public | BindingFlags.Static)
        ?? throw new InvalidOperationException($"{bridgePath} has no Clrpp.Bridge.WeaveAssembly");
    var weave = (delegate* unmanaged<IntPtr, int>)method.MethodHandle.GetFunctionPointer();
    var path = Marshal.StringToCoTaskMemUTF8(Path.GetFullPath(assemblyPath));
    try
    {
        var result = weave(path);
        Console.WriteLine($"{Path.GetFileName(assemblyPath)}: {(result > 0 ? "woven" : result == 0 ? "nothing to weave" : "weaving failed")}");
        return result >= 0;
    }
    finally
    {
        Marshal.FreeCoTaskMem(path);
    }
}

static string ToSignature(TypeReference returnType, IEnumerable<TypeReference> parameterTypes)
{
    var result = ToChar(returnType, 0, out var isResultByPointer).ToString();
    if(isResultByPointer)
    {
        result = "VI";
    }
    foreach(var parameterType in parameterTypes)
    {
        result += ToChar(parameterType, 0, out _);
    }
    return result;
}

static char ToChar(TypeReference type, int depth, out bool isStructByPointer)
{
    isStructByPointer = false;
    while(type is IModifierType modified)
    {
        type = modified.ElementType;
    }
    if(type is ByReferenceType || type is PointerType || type is FunctionPointerType || type is ArrayType)
    {
        return 'I';
    }
    switch(type.FullName)
    {
        case "System.Void":
            return 'V';
        case "System.Int64":
        case "System.UInt64":
            return 'L';
        case "System.Single":
            return 'F';
        case "System.Double":
            return 'D';
        case "System.String":
        case "System.Boolean":
        case "System.Char":
        case "System.SByte":
        case "System.Byte":
        case "System.Int16":
        case "System.UInt16":
        case "System.Int32":
        case "System.UInt32":
        case "System.IntPtr":
        case "System.UIntPtr":
            return 'I';
    }
    var definition = type.Resolve() ?? throw new InvalidOperationException($"cannot resolve {type.FullName}");
    if(definition.IsEnum)
    {
        var underlying = definition.Fields.First(f => !f.IsStatic).FieldType;
        return ToChar(underlying, depth + 1, out _);
    }
    if(!definition.IsValueType)
    {
        return 'I';
    }
    if(depth > MAX_STRUCT_DEPTH)
    {
        throw new InvalidOperationException($"{type.FullName} nests too deep");
    }
    var fields = definition.Fields.Where(f => !f.IsStatic).ToList();
    if(fields.Count == 1)
    {
        return ToChar(fields[0].FieldType, depth + 1, out isStructByPointer);
    }
    isStructByPointer = true;
    return 'I';
}

static string ToCSharp(char code) => code switch
{
    'V' => "void",
    'I' => "int",
    'L' => "long",
    'F' => "float",
    'D' => "double",
    _ => throw new InvalidOperationException($"unknown signature character {code}"),
};

static string ToParameters(string codes) =>
    string.Join(", ", codes.Select((code, index) => $"{ToCSharp(code)} a{index}"));
